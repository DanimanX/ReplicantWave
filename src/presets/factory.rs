fn create_default_steps(pattern: &[(i8, u8, bool, bool, bool)]) -> Vec<Step> {
    let mut steps = vec![Step::default(); MAX_STEPS];
    for (i, p) in pattern.iter().enumerate().take(MAX_STEPS) {
        steps[i] = Step {
            note_offset: p.0,
            velocity: p.1,
            gate: p.2,
            slide: p.3,
            accent: p.4,
            tie: false,
        };
    }
    steps
}

